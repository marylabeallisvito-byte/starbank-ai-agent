"""
backend/agents/prompts.py
=========================
多 Agent 风控决策系统的三个系统提示词（权威版，源自用户提供的详细 Prompt 规范）。

三个 Agent 分工明确、视角互补，共同构成「穿透式风控」的决策大脑：
- 风控 Agent ：信用 / 经营视角 —— 供应链集中度、空壳欺诈、资金链断裂；
- 合规 Agent ：合规 / 反洗钱视角 —— 资金回环、自融穿透(UBO)、设备聚集、PEP；
- 决策 Agent ：综合研判，输出最终裁决（REJECT/FLAGGED/APPROVE），并在末尾
               附带结构化 JSON（decision + suspicious_nodes + suspicious_edges_types）供前端高亮。

提示词设计原则（对齐「可解释性 XAI」目标）：
    所有结论必须【图谱数据锚定】（Grounding），提及风险必须写出节点/边 ID，
    严禁幻觉；输出格式严格约束，便于系统正则提取结构化数据。
"""


