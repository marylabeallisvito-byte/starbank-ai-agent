def get_clause_text(clause_id: str) -> Optional[str]:
    """查询单条法条原文；不存在返回 None（作为「是否存在」的权威判据）。"""
    return LEGAL_CLAUSES.get(clause_id)


def retrieve_clauses(risk_labels: List[str]) -> List[Dict[str, str]]:
    """
    按风险定性标签检索相关法条，返回 [{clause_id, text}]（已按条款号去重、保持顺序稳定）。

    这是「第二个 RAG」的确定性实现：用规则映射而非 LLM 生成，保证检索结果
    可复现、可解释。后续可将 RISK_CLAUSE_MAP 替换为 embedding 向量检索，接口不变。
    """
    seen: Dict[str, str] = {}
    for label in risk_labels or []:
        for clause_id in RISK_CLAUSE_MAP.get(label, []):
            text = LEGAL_CLAUSES.get(clause_id)
            if text and clause_id not in seen:
                seen[clause_id] = text
    return [{"clause_id": k, "text": v} for k, v in seen.items()]


def detect_risk_labels(query: str, graph_json: Dict[str, Any]) -> List[str]:
    """
    从 query 与子图结构启发式推断风险标签（确定性规则，非 LLM），用于定向检索法条。

    依据：子图中出现的边类型（TRANSFER/OWNS/LOGGED_IN）、节点标签（Device）、
    以及节点 risk_flag 标记，映射到反洗钱领域的高危模式。
    """
    labels: List[str] = []
    edge_types = {e.get("type") for e in (graph_json or {}).get("edges", [])}
    node_labels: set = set()
    has_risk_flag = False
    for n in (graph_json or {}).get("nodes", []):
        node_labels.update(n.get("labels", []) or [])
        if (n.get("properties") or {}).get("risk_flag") is True:
            has_risk_flag = True

    q = query or ""
    if "TRANSFER" in edge_types:
        labels += ["资金回环", "大额交易"]
    if "OWNS" in edge_types:
        labels.append("自融穿透")
    if "Device" in node_labels or "LOGGED_IN" in edge_types:
        labels.append("设备聚集")
    if "PEP" in q or "政治" in q or "高管" in q:
        labels.append("PEP")
    if has_risk_flag:
        labels.append("空壳公司")
    return labels


def verify_citations(citations: List[Dict[str, Any]]) -> Dict[str, Any]:
    """
    校验合规 Agent 引用的法条（「引用白名单」兜底）。

    规则：
    - 引用里的「条款号」必须在 LEGAL_CLAUSES 中，否则视为非法引用（幻觉）；
    - 合法引用的原文一律以库为准回填（Agent 只写条款号、不写原文，杜绝编造）。

    Args:
        citations: 合规 Agent 结构化输出里的「法条」列表，每项形如
                   {"条款": "反洗钱法·第十九条"} 或 {"clause_id": "..."}。

    Returns:
        {"valid": [{"clause_id", "text"}, ...], "invalid": [非法条款号, ...]}
    """
    valid: List[Dict[str, str]] = []
    invalid: List[str] = []
    for c in citations or []:
        if not isinstance(c, dict):
            continue
        clause_id = c.get("条款") or c.get("clause_id") or c.get("id") or ""
        clause_id = str(clause_id).strip()
        text = LEGAL_CLAUSES.get(clause_id)
        if text:
            valid.append({"clause_id": clause_id, "text": text})
        elif clause_id:
            invalid.append(clause_id)
    return {"valid": valid, "invalid": invalid}
