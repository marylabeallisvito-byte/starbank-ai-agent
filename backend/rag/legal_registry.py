"""
backend/rag/legal_registry.py
=============================
可验证合规推理的法条库与引用校验（创新点一 · 王牌）。

设计定位
--------
传统合规 Agent 的结论是「自由文本」—— 引用法条时极易产生「引用幻觉」
（编造法条号 / 杜撰条文）。本模块从机制上根治该问题：

    1. 建一座小型、权威的法条库（《反洗钱法》、央行 3 号令、FATF 建议、
       巴塞尔 AML 指南等），每条法条以「条款号 → 原文」的形式固化；
    2. 合规 Agent 不得自由引用，只能从系统检索出的【候选法条白名单】里挑选
       条款号，且【只写条款号、不写原文】；
    3. 引用校验器 `verify_citations` 兜底：任何条款号必须存在于库中，
       原文一律以库为准回填，非法引用被剔除并记录，可现场点开任何一条看原文。

这样「图谱拓扑证据 → 检索真实法条 → 条文 + 证据 → 结论」的链路被强制约束，
每一条合规结论都能回溯到具体 edge_id 与真实法条原文，杜绝黑盒结论。

⚠️ 免责声明（诚实化口径）：本文件中的法条条款号与核心义务真实，措辞为竞赛
演示用途的规范表述；正式部署时应以国家法律法规官方公布文本为准，并定期更新。
"""
